import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const root = fs.mkdtempSync(path.join(os.tmpdir(), 'cc-session-route-'));
process.env.CC_ROOT = root;
const { default: sessionAction } = await import('../lib/routes/sessions.mjs');
const { default: archive } = await import('../lib/routes/archive.mjs');
const { discovered } = await import('../lib/routes/director.mjs');
const { sessionOrigin, sessionTaskResolver } = await import('../lib/session-origin.mjs');
const { enrichSession, decorate } = await import('../lib/session-meta.mjs');
const { freebuffPlan, add: addTask, closeTask } = await import('../lib/tasks.mjs');
const id = 'chat-2026-11-27T10-07-13.427Z';
const session = { slug: id, title: 'Example', mtime: 1, queued: false, archived: false, steps: [] };
const loadSessions = () => [session];
let status, body;
const send = (_res, code, value) => { status = code; body = value; };
const request = async (action, sessionId = id) => {
  status = 0;
  await sessionAction({ req: { method: 'POST', headers: {} }, res: {}, u: { pathname: '/session/meta' }, q: k => ({ p: 'freebuff', id: sessionId, a: action })[k], send, loadSessions, clearSessions() {} });
  return status;
};
try {
  assert.equal(await request('archive'), 200);
  assert.equal(decorate('freebuff', [{ id, ended: true, mtime: 1 }])[0].archived, true);
  assert.equal(await request('unarchive'), 200);
  assert.equal(Boolean(decorate('freebuff', [{ id, ended: true, mtime: 1 }])[0].archived), false);
  assert.equal(await request('delete', 'missing'), 404);
  await archive({ res: {}, u: { pathname: '/session' }, q: k => ({ p: 'freebuff', id })[k], send, loadSessions, worktree: () => '' });
  assert.equal(status, 200);
  assert.equal(body.id, id);
  session.report = 'Completed work'; session.archived = true; session.mtime = Date.now();
  await archive({ res: {}, u: { pathname: '/session' }, q: k => ({ p: 'freebuff', id })[k], send, loadSessions, worktree: () => '' });
  assert.equal(body.live, 'finished');
  assert.equal(discovered(loadSessions).find(x => x.id === id), undefined);
  const thread = '01a21c62-6592-7380-a8ec-0f1da1106f26';
  const log = path.join(root, 'codex.log');
  fs.writeFileSync(log, `session id: ${thread}\n`);
  const belongs = sessionOrigin([{ id: 'cc-one', ranOn: 'codex' }, { id: 'cc-two', ranOn: 'opencode' }, { id: 'cc-three', ranOn: 'claude' }, { id: 'cc-four', ranOn: 'freebuff' }], () => log);
  assert.equal(belongs('codex', { id: thread }), true);
  assert.equal(belongs.task('codex', { id: thread }), undefined);
  fs.writeFileSync(log, `[2026-11-27T10:00:00.000Z] codex exec\nsession id: ${thread}\n`);
  const single = sessionOrigin([{ id: 'cc-one', ranOn: 'codex' }], () => log);
  assert.equal(single.task('codex', { id: thread }), 'cc-one');
  assert.equal(single.task('codex', { id: '01a21c62-6592-7380-a8ec-0f1da1106f27' }), undefined);
  const nextThread = '01a21c62-6592-7380-a8ec-0f1da1106f27';
  fs.appendFileSync(log, `[2026-11-27T11:00:00.000Z] codex exec\nsession id: ${nextThread}\n`);
  const latest = sessionOrigin([{ id: 'cc-one', ranOn: 'codex' }], () => log);
  assert.equal(latest.task('codex', { id: thread }), undefined);
  assert.equal(latest.task('codex', { id: nextThread }), 'cc-one');
  const duplicate = sessionOrigin([{ id: 'cc-one', ranOn: 'codex' }, { id: 'cc-other', ranOn: 'codex' }], () => log);
  assert.equal(duplicate.task('codex', { id: nextThread }), null);
  assert.equal(belongs('codex', { id: '01a21c62-6592-7380-a8ec-0f1da1106f27' }), false);
  assert.equal(belongs('opencode', { title: 'cc-two Task' }), true);
  assert.equal(belongs('opencode', { title: 'cc-two Task', sub: true }), false);
  assert.equal(belongs('opencode', { title: 'cc-two-other Task' }), false);
  assert.equal(belongs('claude', { taskId: 'cc-three' }), true);
  assert.equal(belongs('freebuff', { slug: 'cc-four' }), true);
  assert.equal(belongs('freebuff', { slug: id }), false);
  const retried = sessionOrigin([{ id: 'cc-two' }, { id: 'cc-three', ranOn: 'cursor' }], () => log);
  assert.equal(retried('codex', { id: thread }), true);
  assert.equal(retried('opencode', { title: 'cc-two Task' }), true);
  assert.equal(retried('claude', { taskId: 'cc-three' }), true);
  const resolveTask = sessionTaskResolver([{ id: 'cc-one', ranOn: 'codex', title: 'Codex job' }, { id: 'cc-four', ranOn: 'freebuff', title: 'FB job' }], () => log);
  assert.equal(resolveTask('codex', { id: thread })?.title, 'Codex job');
  assert.equal(resolveTask('freebuff', { slug: 'cc-four' })?.title, 'FB job');
  const activeCliDecision = (_k, _m, _o) => ({ model: 'DeepSeek V4.1 Flash', modelKey: 'm-8db1ccbba6', cost: 2, useLeft: 10, max: 5, clis: [{ pid: 9999, modelKey: 'm-8db1ccbba6', minsLeft: 42, pending: false }] });
  const reuseWait = freebuffPlan({ id: 't1', kind: 'code', provider: 'freebuff' }, { spawnDecision: activeCliDecision, ownPids: new Set([9999]) });
  assert.ok(reuseWait.wait && /42m left in current hour/.test(reuseWait.wait), `Expected wait to reuse 42m CLI, got ${JSON.stringify(reuseWait)}`);
  const externalOnly = freebuffPlan({ id: 't1b', kind: 'code', provider: 'freebuff' }, { spawnDecision: activeCliDecision, ownPids: new Set() });
  assert.equal(externalOnly.spawn, true);
  const parallelSpawn = freebuffPlan({ id: 't2', kind: 'code', provider: 'freebuff', newSession: true }, { spawnDecision: activeCliDecision, ownPids: new Set([9999]) });
  assert.equal(parallelSpawn.spawn, true);
  const expiringDecision = (_k, _m, _o) => ({ model: 'DeepSeek V4.1 Flash', modelKey: 'm-8db1ccbba6', cost: 2, useLeft: 10, max: 5, clis: [{ pid: 9999, modelKey: 'm-8db1ccbba6', minsLeft: 3, pending: false }] });
  const expiringSpawn = freebuffPlan({ id: 't3', kind: 'code', provider: 'freebuff' }, { spawnDecision: expiringDecision, ownPids: new Set([9999]) });
  assert.equal(expiringSpawn.spawn, true);
  const doneFreebuff = enrichSession('freebuff', { id: 's-done', mtime: Date.now() }, { id: 's-done', status: 'done', cli: 'c1' }, { id: 'c1', expiresAt: Date.now() + 600000, exited: false, taskId: null });
  assert.equal(doneFreebuff.cliReusable, false);
  assert.equal(doneFreebuff.minsLeft, null);
  const liveTask = addTask({ title: 'Live Freebuff', text: 'Run live', provider: 'freebuff', cwd: root });
  liveTask.status = 'running';
  liveTask.pid = process.pid;
  const liveLoad = () => [{ slug: liveTask.id, title: 'Read and do the task in the file at: x', mtime: 1, queued: false, archived: false, steps: [] }];
  await archive({ res: {}, u: { pathname: '/session' }, q: k => ({ p: 'freebuff', id: liveTask.id })[k], send, loadSessions: liveLoad, worktree: () => root });
  assert.equal(status, 200);
  assert.equal(body.live, 'running');
  assert.equal(body.title, 'Live Freebuff');
  closeTask(liveTask.id, 'done', 'test cleanup', { panel: true });
  session.report = null; session.archived = false; session.mtime = 1;
  assert.equal(await request('delete'), 200);
} finally {
  fs.rmSync(root, { recursive: true, force: true });
}
